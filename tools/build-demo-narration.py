"""Build the finished demo voice clips; the app only plays the bundled MP3 files.

Install kokoro-onnx and soundfile in a build-only environment. Supply the model and
voices from https://github.com/thewh1teagle/kokoro-onnx/releases/tag/model-files-v1.1.
Run with --model kokoro-v1.0.onnx --voices voices-v1.0.bin. No model ships in the app.
tools/demo-narration.json contains the captions exported from the live 46-step tour.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re
import shutil
import subprocess
import tempfile

import numpy as np
import onnxruntime as ort
import soundfile as sf
from kokoro_onnx import Kokoro


ROOT = Path(__file__).resolve().parents[1]


def spoken(text):
    text = re.sub(r"(\d+)\s*[–−-]\s*(\d+)px", r"\1 to \2 pixels", text)
    text = re.sub(r"(\d+)px", r"\1 pixels", text)
    text = text.replace('%', ' percent').replace('✎', 'pencil').replace('10 MB', '10 megabyte')
    text = text.replace('tweakcn', 'tweak C N').replace('Samestate', 'Same state')
    for word, reading in {'CSS': 'C S S', 'AI': 'A I', 'RTL': 'right to left',
                          'HTML': 'H T M L', 'JSON': 'jay son', 'CSV': 'C S V',
                          'PNG': 'P N G', 'PDF': 'P D F'}.items():
        text = re.sub(r'\b' + word + r'\b', reading, text)
    return text


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--model', type=Path, required=True)
    parser.add_argument('--voices', type=Path, required=True)
    parser.add_argument('--ffmpeg', default=shutil.which('ffmpeg') or '/opt/homebrew/bin/ffmpeg')
    parser.add_argument('--voice', default='af_heart')
    parser.add_argument('--speed', type=float, default=1.0)
    parser.add_argument('--help-catalog', type=Path, help='Build app-wide help audio from a feature-help JSON catalogue instead.')
    args = parser.parse_args()
    source = json.loads((args.help_catalog or ROOT / 'tools/demo-narration.json').read_text())
    if not args.help_catalog:
        assert len(source['clips']) == 46, 'Export all 46 current demo captions first.'
    output = ROOT / ('extension/help/narration' if args.help_catalog else 'extension/demo/narration')
    output.mkdir(parents=True, exist_ok=True)
    options = ort.SessionOptions()
    options.intra_op_num_threads = 4
    options.inter_op_num_threads = 1
    session = ort.InferenceSession(str(args.model), sess_options=options, providers=['CPUExecutionProvider'])
    voice = Kokoro.from_session(session, str(args.voices))
    manifest = {'version': 1, 'voice': f'Kokoro {args.voice}', 'clips': []}
    digest = hashlib.sha256(json.dumps(source, sort_keys=True).encode() + args.voice.encode() + str(args.speed).encode()).hexdigest()[:16]
    manifest['build'] = digest
    built = {}
    with tempfile.TemporaryDirectory(prefix='samestate-demo-voice-') as temp:
        for index, item in enumerate(source['clips']):
            clip = dict(item)
            for prefix in ['', 'extension'] if item.get('extensionCaption') else ['']:
                caption = item['extensionCaption' if prefix else 'caption']
                filename = item['extensionFile' if prefix else 'file']
                text = spoken(item['title'] + '. ' + caption)
                if filename in built:
                    clip['duration'] = built[filename]
                    clip['speech'] = text
                    continue
                samples, rate = voice.create(text, voice=args.voice, speed=args.speed, lang='en-us')
                samples = np.concatenate([np.zeros(int(rate * .12)), samples, np.zeros(int(rate * .20))])
                raw = Path(temp) / 'clip.wav'
                sf.write(raw, samples, rate)
                subprocess.run([args.ffmpeg, '-y', '-loglevel', 'error', '-i', str(raw),
                                '-af', 'highpass=f=70,loudnorm=I=-18:TP=-2:LRA=7',
                                '-ar', '44100', '-ac', '1', '-c:a', 'libmp3lame', '-b:a', '64k',
                                str(output / filename)], check=True)
                clip['extensionDuration' if prefix else 'duration'] = round(len(samples) / rate, 3)
                clip['extensionSpeech' if prefix else 'speech'] = text
                built[filename] = round(len(samples) / rate, 3)
                print(f'{index + 1:03d}/{len(source["clips"])} {filename}: {len(samples) / rate:.1f}s', flush=True)
            manifest['clips'].append(clip)
    namespace = 'samestateFeatureHelpNarration' if args.help_catalog else 'samestateDemoNarration'
    (output / 'manifest.js').write_text('/* Generated by tools/build-demo-narration.py. */\nwindow.' + namespace + ' = Object.freeze(' + json.dumps(manifest, ensure_ascii=False, indent=2) + ');\n')
    shutil.copytree(output, ROOT / 'docs' / output.relative_to(ROOT / 'extension'), dirs_exist_ok=True)
    print(f'Bundled {len(built)} finished narration clips in both builds.', flush=True)


if __name__ == '__main__':
    main()
